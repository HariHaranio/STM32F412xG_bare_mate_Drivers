#include "TIM2_Driver.h"
#include "NVIC_driver.h"
#include "main.h"

void TIM2_Init(TIM2_Config_T *TIM2_Config)
{
    if (!(TIM2_Config)){
        return;
    }

    /* Enable TIM2 clock */
    RCC_Enable_TIM2();

    /* Disable TIM2 before configuration */
    TIM2->TIMx_CR1 &= ~TIM_CR1_CEN;

    /* Configure Prescaler */
    TIM2->TIMx_PSC = TIM2_Config->TIM2_Prescaler;

    /* Configure Auto Reload */
    TIM2->TIMx_ARR = TIM2_Config->TIM2_AutoReload;

    /*
     * Generate update event.
     *
     * This transfers the PSC value into the prescaler.
     */
    TIM2->TIMx_EGR |= TIM_EGR_UG;

    /*
     * Clear UIF generated by UG.
     */
    TIM2->TIMx_SR &= ~TIM_SR_UIF;

    /*
     * Enable TIM2 Update Interrupt.
     */
    TIM2->TIMx_DIER |= TIM_DIER_UIE;

    /*
     * Enable TIM2 interrupt inside NVIC.
     */
    NVIC_EnableIRQ(TIM2_IRQn);
}


void TIM2_Start(void)
{
    TIM2->TIMx_CR1 |= TIM_CR1_CEN;
}


void TIM2_Stop(void)
{
    TIM2->TIMx_CR1 &= ~TIM_CR1_CEN;
}


void TIM2_EnableInterrupt(void)
{
    TIM2->TIMx_DIER |= TIM_DIER_UIE;
}


void TIM2_DisableInterrupt(void)
{
    TIM2->TIMx_DIER &= ~TIM_DIER_UIE;
}


void TIM2_ClearUpdateFlag(void)
{
    TIM2->TIMx_SR &= ~TIM_SR_UIF;
}


/* =========================================================
 * TIM2 Interrupt Handler
 * ========================================================= */
volatile uint32_t TIM2_Tick = 0;

void TIM2_IRQHandler(void)
{
    if (TIM2->TIMx_SR & TIM_SR_UIF)
    {
        TIM2->TIMx_SR &= ~TIM_SR_UIF;

        TIM2_Tick++;
    }
}


uint32_t TIM2_GetTick(void){
    return TIM2_Tick;
}


void TIM2_DelayMs(uint32_t delay)
{
    uint32_t start = TIM2_Tick;

    while ((TIM2_Tick - start) < delay);
}

void TIM2_DelayUs(uint32_t us)
{
    uint32_t start;
    uint32_t current;
    uint32_t elapsed;

    if (us == 0U)
    {
        return;
    }

    while (us >= 1000U)
    {
        TIM2_DelayMs(1U);
        us -= 1000U;
    }

    if (us > 0U)
    {
        start = TIM2->TIMx_CNT;

        while (1)
        {
            current = TIM2->TIMx_CNT;

            if (current >= start)
            {
                elapsed = current - start;
            }
            else
            {
                elapsed = (1000U - start) + current;
            }

            if (elapsed >= us)
            {
                break;
            }
        }
    }
}
